static constexpr u32 BUILTIN_GLYPH_W = 8;
static constexpr u32 BUILTIN_GLYPH_H = 8;
static constexpr u32 BUILTIN_FIRST_CHAR = 32;
static constexpr u32 BUILTIN_LAST_CHAR = 126;
static constexpr u32 BUILTIN_CHAR_COUNT = BUILTIN_LAST_CHAR - BUILTIN_FIRST_CHAR + 1;

bool BitmapFont::load_builtin(float font_size) {
    font_size_ = font_size;
    float scale = font_size / static_cast<float>(BUILTIN_GLYPH_H);

    // Layout: 16 chars per row in the atlas
    u32 chars_per_row = 16;
    u32 rows = (BUILTIN_CHAR_COUNT + chars_per_row - 1) / chars_per_row;
    atlas_width_ = chars_per_row * BUILTIN_GLYPH_W;
    atlas_height_ = rows * BUILTIN_GLYPH_H;

    atlas_.resize(atlas_width_ * atlas_height_, 0);

    for (u32 i = 0; i < BUILTIN_CHAR_COUNT; ++i) {
        u32 col = i % chars_per_row;
        u32 row = i / chars_per_row;
        u32 px = col * BUILTIN_GLYPH_W;
        u32 py = row * BUILTIN_GLYPH_H;

        // Rasterize 8x8 bitmap glyph into atlas
        const u8* glyph_data = BUILTIN_FONT_DATA[i];
        for (u32 y = 0; y < BUILTIN_GLYPH_H; ++y) {
            u8 bits = glyph_data[y];
            for (u32 x = 0; x < BUILTIN_GLYPH_W; ++x) {
                bool set = (bits >> (7 - x)) & 1;
                atlas_[(py + y) * atlas_width_ + (px + x)] = set ? 255 : 0;
            }
        }

        // Create glyph entry
        Glyph g;
        g.codepoint = BUILTIN_FIRST_CHAR + i;
        g.x0 = static_cast<float>(px) / static_cast<float>(atlas_width_);
        g.y0 = static_cast<float>(py) / static_cast<float>(atlas_height_);
        g.x1 = static_cast<float>(px + BUILTIN_GLYPH_W) / static_cast<float>(atlas_width_);
        g.y1 = static_cast<float>(py + BUILTIN_GLYPH_H) / static_cast<float>(atlas_height_);
        g.width = static_cast<float>(BUILTIN_GLYPH_W) * scale;
        g.height = static_cast<float>(BUILTIN_GLYPH_H) * scale;
        g.x_offset = 0.0f;
        g.y_offset = 0.0f;
        g.advance = g.width;

        glyphs_[g.codepoint] = g;
    }

    line_height_ = static_cast<float>(BUILTIN_GLYPH_H) * scale * 1.25f;
    base_line_ = static_cast<float>(BUILTIN_GLYPH_H) * scale;

    NX_INFO("BitmapFont: loaded built-in {}x{} font ({} glyphs, atlas {}x{})",
            BUILTIN_GLYPH_W, BUILTIN_GLYPH_H, BUILTIN_CHAR_COUNT,
            atlas_width_, atlas_height_);
    return true;
}

bool BitmapFont::load_bmfont(const std::string& fnt_path) {
    std::ifstream file(fnt_path);
    if (!file.is_open()) {
        NX_ERROR("BitmapFont: cannot open '{}'", fnt_path);
        return false;
    }

    std::string line;
    u32 atlas_w = 0, atlas_h = 0;

    while (std::getline(file, line)) {
        std::istringstream iss(line);
        std::string tag;
        iss >> tag;

        if (tag == "common") {
            // Parse: common lineHeight=X base=Y scaleW=W scaleH=H
            std::string token;
            while (iss >> token) {
                if (token.substr(0, 11) == "lineHeight=") line_height_ = std::stof(token.substr(11));
                else if (token.substr(0, 5) == "base=") base_line_ = std::stof(token.substr(5));
                else if (token.substr(0, 7) == "scaleW=") atlas_w = std::stoul(token.substr(7));
                else if (token.substr(0, 7) == "scaleH=") atlas_h = std::stoul(token.substr(7));
            }
        } else if (tag == "char") {
            Glyph g{};
            float x = 0, y = 0, w = 0, h = 0;
            std::string token;
            while (iss >> token) {
                if (token.substr(0, 3) == "id=") g.codepoint = std::stoul(token.substr(3));
                else if (token.substr(0, 2) == "x=") x = std::stof(token.substr(2));
                else if (token.substr(0, 2) == "y=") y = std::stof(token.substr(2));
                else if (token.substr(0, 6) == "width=") w = std::stof(token.substr(6));
                else if (token.substr(0, 7) == "height=") h = std::stof(token.substr(7));
                else if (token.substr(0, 8) == "xoffset=") g.x_offset = std::stof(token.substr(8));
                else if (token.substr(0, 8) == "yoffset=") g.y_offset = std::stof(token.substr(8));
                else if (token.substr(0, 9) == "xadvance=") g.advance = std::stof(token.substr(9));
            }
            if (atlas_w > 0 && atlas_h > 0) {
                g.x0 = x / static_cast<float>(atlas_w);
                g.y0 = y / static_cast<float>(atlas_h);
                g.x1 = (x + w) / static_cast<float>(atlas_w);
                g.y1 = (y + h) / static_cast<float>(atlas_h);
            }
            g.width = w;
            g.height = h;
            glyphs_[g.codepoint] = g;
        }
    }

    atlas_width_ = atlas_w;
    atlas_height_ = atlas_h;
    // Note: the actual atlas texture (.png) must be loaded separately and uploaded to GPU
    NX_INFO("BitmapFont: loaded BMFont '{}' ({} glyphs)", fnt_path, glyphs_.size());
    return !glyphs_.empty();
}

const Glyph* BitmapFont::get_glyph(u32 codepoint) const {
    auto it = glyphs_.find(codepoint);
    return (it != glyphs_.end()) ? &it->second : nullptr;
}

Vec2 BitmapFont::measure_text(const std::string& text) const {
    float x = 0.0f;
    float max_x = 0.0f;
    float y = line_height_;

    for (size_t i = 0; i < text.size(); ++i) {
        char ch = text[i];
        if (ch == '\n') {
            max_x = std::max(max_x, x);
            x = 0.0f;
            y += line_height_;
            continue;
        }
        const Glyph* g = get_glyph(static_cast<u32>(ch));
        if (g) {
            x += g->advance;
        }
    }
    max_x = std::max(max_x, x);
    return {max_x, y};
}

float BitmapFont::get_kerning(u32 /*left*/, u32 /*right*/) const {
    // Kerning pairs not yet supported for built-in font
    return 0.0f;
}

std::vector<BitmapFont::TextVertex> BitmapFont::generate_vertices(
    const std::string& text, Vec2 position) const
{
    std::vector<TextVertex> vertices;
    vertices.reserve(text.size() * 6); // 6 vertices per quad (2 triangles)

    float cursor_x = position.x;
    float cursor_y = position.y;

    for (size_t i = 0; i < text.size(); ++i) {
        char ch = text[i];
        if (ch == '\n') {
            cursor_x = position.x;
            cursor_y += line_height_;
            continue;
        }

        const Glyph* g = get_glyph(static_cast<u32>(ch));
        if (!g) continue;

        float x0 = cursor_x + g->x_offset;
        float y0 = cursor_y + g->y_offset;
        float x1 = x0 + g->width;
        float y1 = y0 + g->height;

        // Two triangles per glyph quad
        vertices.push_back({x0, y0, g->x0, g->y0});
        vertices.push_back({x1, y0, g->x1, g->y0});
        vertices.push_back({x1, y1, g->x1, g->y1});

        vertices.push_back({x0, y0, g->x0, g->y0});
        vertices.push_back({x1, y1, g->x1, g->y1});
        vertices.push_back({x0, y1, g->x0, g->y1});

        cursor_x += g->advance;
    }

    return vertices;
}

